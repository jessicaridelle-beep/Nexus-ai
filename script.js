// Add your deployed Cloudflare Worker URL here after setup.
// Example: https://nexus-ai-api.YOUR-SUBDOMAIN.workers.dev
const NEXUS_API_URL = "https://nexus-ai-api.jessicaridelle.workers.dev";

const form = document.getElementById("chatForm");
const input = document.getElementById("promptInput");
const content = document.getElementById("chatContent");
const sendButton = form.querySelector("button");
const chatNote = document.querySelector(".chat-note");
const conversation = [];

function addMessage(role, text) {
  if (role === "user") {
    const message = document.createElement("div");
    message.className = "user-message";
    message.textContent = text;
    content.appendChild(message);
    return;
  }

  const reply = document.createElement("div");
  reply.className = "assistant-message";
  reply.style.marginTop = "18px";
  const icon = document.createElement("span");
  icon.className = "message-icon";
  icon.textContent = "N";
  const body = document.createElement("div");
  const title = document.createElement("b");
  title.textContent = "NEXUS AI";
  const paragraph = document.createElement("p");
  paragraph.textContent = text;
  body.append(title, paragraph);
  reply.append(icon, body);
  content.appendChild(reply);
}

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  const value = input.value.trim();
  if (!value || sendButton.disabled) return;

  addMessage("user", value);
  input.value = "";
  if (!NEXUS_API_URL) {
    addMessage("assistant", "The website is ready for its AI connection, but the private backend URL has not been added yet. Follow the setup guide in the GitHub repository to finish connecting me.");
    content.scrollIntoView({ behavior: "smooth", block: "end" });
    return;
  }

  const normalized = value.toLowerCase().replace(/[^a-z0-9 ]/g, "").trim();
  if (/(who created you|who made you|who built you|who is your creator)/.test(normalized)) {
    addMessage("assistant", "I was created by the owner of the GitHub account jessicaridelle-beep, with the help of ChatGPT. 😎");
    content.scrollIntoView({ behavior: "smooth", block: "end" });
    return;
  }

  conversation.push({ role: "user", content: value });
  sendButton.disabled = true;
  sendButton.textContent = "…";
  chatNote.textContent = "NEXUS is thinking…";

  try {
    const response = await fetch(NEXUS_API_URL, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ messages: conversation.slice(-12) })
    });
    const data = await response.json();
    if (!response.ok) throw new Error(data.error || "The AI service returned an error.");
    if (typeof data.reply !== "string" || !data.reply.trim()) throw new Error("The AI returned an empty response.");

    conversation.push({ role: "assistant", content: data.reply });
    addMessage("assistant", data.reply);
    chatNote.textContent = "AI responses are generated by the NEXUS backend.";
  } catch (error) {
    conversation.pop();
    addMessage("assistant", error.message || "I couldn't reach the AI service. Please try again.");
    chatNote.textContent = "Connection issue — check the backend setup and try again.";
  } finally {
    sendButton.disabled = false;
    sendButton.textContent = "↑";
    content.scrollIntoView({ behavior: "smooth", block: "end" });
  }
});
